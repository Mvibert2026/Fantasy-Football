/**
 * Embeds the default league's export artifacts into a single generated TS module,
 * so the standalone build (`npm run build:standalone`) has zero runtime `fetch()`
 * calls for data -- everything is a JS object literal baked in at build time.
 *
 * Deliberately excludes weekly_finishes.json (8.9MB) and season_stats.json
 * (2.3MB): those two feed only PlayerDetail's sections 7/8 (season history), are
 * ~85% of this repo's total export weight, and the standalone target's whole
 * point is "small enough to email/open on a phone." The standalone build's
 * ui/data/playerHistory.standalone.ts alias renders those two sections as an
 * honest "not included in this static snapshot" instead of fetching them --
 * reusing PlayerDetail's existing error-state branch, not a new code path.
 *
 * Excludes player_descriptions.json too: grepped, nothing in ui/ reads it yet.
 *
 * Run directly (`node scripts/build-standalone-data.mjs`) or via the
 * `prebuild:standalone` npm script, which runs it before `vite build`.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// Repo root's data/export/ -- the same single source of truth
// scripts/sync-exports.mjs reads from, not a frontend-local copy.
const srcDir = join(root, '..', 'data', 'export');
const outFile = join(root, 'ui', 'data', 'standaloneEmbedded.generated.ts');

const REQUIRED = ['board', 'league', 'glossary', 'nulls', 'availability', 'opponents'];
const OPTIONAL = ['strategies', 'rosters'];

function readJson(name) {
  const path = join(srcDir, `${name}.json`);
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch (err) {
    if (err.code === 'ENOENT') return null;
    throw new Error(`[build-standalone-data] ${path} is not valid JSON: ${err.message}`);
  }
}

function artifactEntry(name, parsed) {
  if (!parsed) return null;
  const contractVersion = parsed?.contract_version ?? null;
  const generatedUtc = parsed?.generated_utc ?? null;
  return {
    file: `embedded:${name}.json`,
    contract_version: contractVersion,
    generated_utc: generatedUtc,
    league_id: parsed?.league_id ?? null,
    run_id:
      contractVersion && generatedUtc
        ? `${name}@${contractVersion}+${generatedUtc}`
        : `${name}@unversioned`,
  };
}

function main() {
  const data = {};
  const artifacts = {};

  for (const name of REQUIRED) {
    const parsed = readJson(name);
    if (!parsed) {
      throw new Error(
        `[build-standalone-data] ${name}.json is required and was not found under ${srcDir}. ` +
          `Run the backend export first.`,
      );
    }
    data[name] = parsed;
    artifacts[name] = artifactEntry(name, parsed);
  }

  for (const name of OPTIONAL) {
    const parsed = readJson(name);
    data[name] = parsed;
    if (parsed) artifacts[name] = artifactEntry(name, parsed);
  }

  const manifest = { synced_utc: new Date().toISOString(), artifacts };

  const banner =
    `// AUTO-GENERATED by scripts/build-standalone-data.mjs. Do not hand-edit --\n` +
    `// regenerate with \`npm run build:standalone\` (or the script directly), which\n` +
    `// re-reads ../data/export/*.json fresh every time. See that script's own doc\n` +
    `// comment for which artifacts are embedded and which are deliberately not.\n` +
    `// Embedded at: ${manifest.synced_utc}\n`;

  const body =
    `import type { Dataset } from './load';\n\n` +
    `export const STANDALONE_DATASET: Dataset = {\n` +
    `  manifest: ${JSON.stringify(manifest)},\n` +
    `  board: ${JSON.stringify(data.board)},\n` +
    `  league: ${JSON.stringify(data.league)},\n` +
    `  glossary: ${JSON.stringify(data.glossary)},\n` +
    `  nulls: ${JSON.stringify(data.nulls)},\n` +
    `  strategies: ${JSON.stringify(data.strategies ?? null)},\n` +
    `  availability: ${JSON.stringify(data.availability)},\n` +
    `  opponents: ${JSON.stringify(data.opponents)},\n` +
    `  rosters: ${JSON.stringify(data.rosters ?? null)},\n` +
    // No news corpus exists (see ui/data/load.ts's fetchFeedOrEmpty) -- the same
    // honest-empty shape it already falls back to on a 404, not a new claim.
    `  feed: { contract_version: 'absent', generated_utc: 'never', items: [] },\n` +
    `};\n`;

  writeFileSync(outFile, banner + '\n' + body);

  const totalBytes = Object.values(data)
    .filter(Boolean)
    .reduce((sum, v) => sum + Buffer.byteLength(JSON.stringify(v)), 0);
  console.log(
    `[build-standalone-data] wrote ${outFile.replace(root + '/', '')} ` +
      `(${(totalBytes / 1024 / 1024).toFixed(2)} MB of embedded JSON, ` +
      `board.generated_utc=${data.board.generated_utc})`,
  );
}

main();
